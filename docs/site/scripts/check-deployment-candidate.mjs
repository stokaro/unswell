#!/usr/bin/env node
// The post-deploy smoke check: fetch the published apex and confirm a reader
// lands on the documentation.
//
// A green deploy job means GitHub accepted an artifact, not that the domain
// serves it. The two failures this catches are the ones that look fine in the
// workflow log: the apex answering GitHub's own 404 page because the CNAME did
// not survive the assembly, and the apex redirecting to a version folder that
// the assembly never wrote.
//
// Pages serves a new artifact a few seconds after the API reports success, so
// the check retries before it fails.
import { Origin } from '../src/lib/docs-origin.mjs';

const DEFAULT_ATTEMPTS = 10;
const DEFAULT_DELAY_MS = 6000;

// REDIRECT_RE reads the version out of the apex stub. The stub is generated by
// gen-versions.mjs, which writes the same target into the refresh header, the
// canonical link and the inline script, so matching the canonical link is
// enough to learn which version the apex serves.
const REDIRECT_RE = /<link rel="canonical" href="\/([^/"]+)\/"/;

export function readRedirectTarget(html) {
	const match = REDIRECT_RE.exec(html);
	return match ? match[1] : null;
}

// evaluate decides one attempt. It is separate from the fetching so the
// selftest can exercise every outcome without a network.
export function evaluate({ rootStatus, rootBody, versionStatus, versionBody }, expectedVersions) {
	if (rootStatus !== 200) return { ok: false, reason: `the apex answered ${rootStatus}` };
	const target = readRedirectTarget(rootBody);
	if (target === null) return { ok: false, reason: 'the apex is not the generated redirect stub' };
	if (expectedVersions.length > 0 && !expectedVersions.includes(target)) {
		return { ok: false, reason: `the apex redirects to ${target}, which this deploy did not build` };
	}
	if (versionStatus !== 200) return { ok: false, reason: `${target} answered ${versionStatus}` };
	if (!versionBody.includes('Unswell')) {
		return { ok: false, reason: `${target} does not look like the documentation` };
	}
	return { ok: true, version: target };
}

async function attempt(expectedVersions) {
	const rootResponse = await fetch(`${Origin}/`, { redirect: 'follow' });
	const rootBody = await rootResponse.text();
	const target = readRedirectTarget(rootBody);
	if (rootResponse.status !== 200 || target === null) {
		return evaluate(
			{ rootStatus: rootResponse.status, rootBody, versionStatus: 0, versionBody: '' },
			expectedVersions
		);
	}
	const versionResponse = await fetch(`${Origin}/${target}/`, { redirect: 'follow' });
	const versionBody = await versionResponse.text();
	return evaluate(
		{
			rootStatus: rootResponse.status,
			rootBody,
			versionStatus: versionResponse.status,
			versionBody,
		},
		expectedVersions
	);
}

function sleep(ms) {
	return new Promise((done) => {
		setTimeout(done, ms);
	});
}

export async function waitForDeployment(expectedVersions, attempts = DEFAULT_ATTEMPTS, delay = DEFAULT_DELAY_MS) {
	let last = { ok: false, reason: 'no attempt was made' };
	for (let i = 0; i < attempts; i += 1) {
		if (i > 0) await sleep(delay);
		try {
			last = await attempt(expectedVersions);
		} catch (error) {
			last = { ok: false, reason: `request failed: ${error.message}` };
		}
		if (last.ok) return last;
		console.log(`attempt ${i + 1}/${attempts}: ${last.reason}`);
	}
	return last;
}

function selftest() {
	const assert = (condition, message) => {
		if (!condition) throw new Error(message);
	};

	const stub = '<link rel="canonical" href="/v0.1.0-alpha.3/" />';
	assert(readRedirectTarget(stub) === 'v0.1.0-alpha.3', 'the target is read from the stub');
	assert(readRedirectTarget('<html></html>') === null, 'a page that is not the stub has no target');

	const good = {
		rootStatus: 200,
		rootBody: stub,
		versionStatus: 200,
		versionBody: '<title>Overview | Unswell</title>',
	};
	assert(evaluate(good, ['edge', 'v0.1.0-alpha.3']).ok, 'a served deployment passes');
	assert(evaluate(good, []).ok, 'an empty expectation accepts any built version');
	assert(!evaluate({ ...good, rootStatus: 404 }, []).ok, 'a 404 apex fails');
	assert(!evaluate({ ...good, rootBody: '<html>GitHub Pages</html>' }, []).ok, 'a foreign apex page fails');
	assert(!evaluate({ ...good, versionStatus: 404 }, []).ok, 'a missing version folder fails');
	assert(!evaluate({ ...good, versionBody: 'nothing here' }, []).ok, 'a page without the product name fails');
	assert(
		evaluate(good, ['edge']).reason.includes('did not build'),
		'a version this deploy did not build fails and says so'
	);
	console.log('check-deployment-candidate.mjs --selftest: OK');
}

async function main() {
	if (process.argv.includes('--selftest')) {
		selftest();
		return;
	}
	const index = process.argv.indexOf('--expected-versions');
	const expectedVersions =
		index === -1 ? [] : process.argv[index + 1].split(/[\s,]+/).filter((value) => value !== '');
	const result = await waitForDeployment(expectedVersions);
	if (!result.ok) {
		console.error(`deployment check failed: ${result.reason}`);
		process.exitCode = 1;
		return;
	}
	console.log(`${Origin}/ serves ${result.version}`);
}

if (process.argv[1] && process.argv[1].endsWith('check-deployment-candidate.mjs')) {
	await main();
}
