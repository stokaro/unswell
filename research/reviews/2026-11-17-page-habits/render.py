#!/usr/bin/env python3
"""Write RESULTS.md of the record of two habits of a page from the recounted numbers.

verify.py calls render() with what it recounted from the data; this file holds no number of its own.
"""

LABELS = {
    "set-s": "Posts of the style-guide set",
    "human-blog": "Blog posts that people wrote before November 2022",
    "human-styled": "Articles that people wrote under a style guide",
    "human-docs": "Documentation pages that people wrote before November 2022",
    "model-guided-1": "Texts of the first writer model under a style guide",
    "model-guided-2": "Texts of the second writer model under a style guide",
    "model-plain-1": "Texts of the first writer model without a style guide",
    "model-plain-2": "Texts of the second writer model without a style guide",
    "fresh-1": "Fresh texts of the first writer model under a style guide",
    "fresh-2": "Fresh texts of the second writer model under a style guide",
    "public-today": "Pages of public repositories today",
    "panel": "Pages of the panel corpus that three models wrote or polished",
}
PARTS = {"fitting": "The fitting parts", "measured": "The measured parts", "whole": "Sets without parts"}
NOTES = {
    "fitting": "The definitions and the limits of both rules were chosen on these pages.",
    "measured": "No definition and no limit was chosen on these pages. The bars are read here.",
    "whole": "These sets have no parts and carry no bar.",
}


def percent(value):
    return f"{100 * value:.1f}%"


def cell(value, interval=True):
    text = f"{value['count']} of {value['of']}, {percent(value['share'])}"
    if interval:
        text += f" ({percent(value['interval'][0])} to {percent(value['interval'][1])})"
    return text


def bars_table(result):
    lines = ["| Bar | Number | Limit | Holds |", "| --- | --- | --- | --- |"]
    for bar in result["bars"]:
        name = bar["bar"]
        for key, label in LABELS.items():
            name = name.replace(key, label[0].lower() + label[1:])
        for rule in result["rules"].values():
            name = name.replace(rule, f"`{rule}`")
        lines.append(f"| {name[0].upper() + name[1:]} | {cell(bar['value'])} | {bar['kind']} {percent(bar['limit'])} | "
                     f"{'yes' if bar['holds'] else '**no**'} |")
    return lines


def sets_table(result, part):
    lines = ["| Pages | Paragraphs end on a denial | One formal register | Either |", "| --- | --- | --- | --- |"]
    for key, label in LABELS.items():
        found = result["sets"].get(f"{key}/{part}")
        if found:
            lines.append(f"| {label} | {cell(found['denial'], False)} | {cell(found['register'], False)} | {cell(found['either'], False)} |")
    return lines


def pairs_table(result):
    lines = ["| Part | Pairs | Rule | Reported before | Reported after | Lost the finding | Gained it |",
             "| --- | ---: | --- | ---: | ---: | ---: | ---: |"]
    for part, found in result["pairs"].items():
        for key, rule in result["rules"].items():
            numbers = found[key]
            lines.append(f"| {part.capitalize()} | {found['pairs']:,} | `{rule}` | {numbers['before']} | {numbers['after']} | "
                         f"{numbers['lost']} | {numbers['gained']} |")
    return lines


def render(result):
    rules = result["rules"]
    lines = ["# Results: two habits of a page", "",
             "Generated by `verify.py --write` from the data of this record. Do not edit.", "",
             f"The rules are `{rules['denial']}` and `{rules['register']}`. A page counts for a rule when the rule reports it.", "",
             "## The bars", "",
             f"{result['bars_held']} of {result['bars_total']} bars hold. They were written on issue 603 before the run on the measured parts.",
             ""]
    lines += bars_table(result)
    fresh, documentation = result["fresh_together"], result["documentation_together"]
    lines += ["", f"The fresh model texts of both writers together: `{rules['register']}` reports {cell(fresh['register'])}, "
              f"and `{rules['denial']}` {cell(fresh['denial'], False)}.", "",
              f"All documentation pages of people, both parts: `{rules['denial']}` reports {cell(documentation['denial'], False)}, "
              f"and `{rules['register']}` {cell(documentation['register'], False)}."]
    for part in ("measured", "fitting", "whole"):
        lines += ["", f"## {PARTS[part]}", "", NOTES[part], ""]
        lines += sets_table(result, part)
    lines += ["", "## Files before and after a commit that removes AI-sounding wording", "",
              "The reference of ADR 0056, without the commits that carry an assistant's co-author trailer. A file lost the finding "
              "when the rule reports it before the commit and not after it.", ""]
    lines += pairs_table(result)
    return "\n".join(lines) + "\n"
