#!/usr/bin/env python3
"""Write RESULTS.md of the record of three pilots of revising a post from the recounted numbers.

verify.py calls render() with what it recounted from the data; this file holds no number of its own.
"""

ARMS = {
    "closing-sentences": "By the report, with the closing sentences listed",
    "manner": "In the manner of two posts of people",
}


def rules_table(result):
    lines = ["| Way of revising | Posts revised | Posts with closing denials | Closing sentences listed | Posts in one register | Median index |",
             "| --- | ---: | --- | --- | --- | --- |"]
    for arm, label in ARMS.items():
        found = result["arms"][arm]
        before, after = found["before"], found["after"]
        change = lambda key: f"{before[key]} to {after[key]}"
        lines.append(f"| {label} | {found['revised']} of {found['posts']} | {change('posts_with_closing_denials')} | "
                     f"{change('closing_sentences')} | {change('posts_in_one_register')} | {change('median_index')} |")
    return lines


def panel_table(result):
    lines = ["| Posts | Text | " + " | ".join(f"`{judge}` alone" for judge in result["judges"]) + " | The three together |",
             "| --- | --- |" + " ---: |" * (len(result["judges"]) + 1)]
    every = result["as_it_is"]
    lines.append("| All 40 | As it is | " + " | ".join(str(every["alone"][judge]) for judge in result["judges"]) + f" | {every['together']} |")
    for arm, label in ARMS.items():
        found = result["arms"][arm]
        for text, key in (("As it is", "picked_as_it_is"), (label, "picked_revised")):
            cells = [str(found[key]["alone"][judge]) if judge in found[key]["alone"] else "not asked" for judge in result["judges"]]
            together = str(found[key]["together"]) if len(found["judges"]) == len(result["judges"]) else "not asked"
            lines.append(f"| The {found['revised']} that were revised | {text} | " + " | ".join(cells) + f" | {together} |")
    return lines


def render(result):
    rounds = result["rounds"]
    first = result["arms"]["closing-sentences"]
    strict = result["judges"][0]
    lines = ["# Results: three pilots of revising a post", "",
             "Generated by `verify.py --write` from the data of this record. Do not edit.", "",
             "All numbers are on the 40 posts of the fitting half of the style-guide set. No bar was set: these are pilots.", "",
             "## What the two rules reported before and after", ""]
    lines += rules_table(result)
    lines += ["", "## What blind judges named", "",
              "Each post stands against three blog posts that people wrote. A judge picks the post when it names the post in more "
              "pairs than the human post; the three together pick it when their votes for it outnumber their votes for the human "
              "posts.", ""]
    lines += panel_table(result)
    lines += ["", f"Of the {3 * first['revised']} pairs with a post revised by the report, `{strict}` named the post in "
              f"{first['picked_revised']['pairs_named_post'][strict]}.", "",
              "## Revising in rounds by the judge's remarks", "",
              f"{rounds['posts']} posts, each judged as it is and after each of four revisions, in two pairs: {rounds['judgments']} "
              f"judgments. The judge named the post in {rounds['named_post']} of them. After the last round it named "
              f"{rounds['posts'] - rounds['posts_not_named_after_the_last_round']} of the {rounds['posts']} posts.", "",
              "## A model's text on the subject of a human post", "",
              "Texts that two models wrote under a style guide from the outline of a human post, each against that post. These "
              "answers are from the first reading of the fitting half, not from the pilots.", "",
              "| Judge | Pairs | Named the model's text |", "| --- | ---: | ---: |"]
    lines += [f"| `{judge}` | {found['pairs']} | {found['named_model']} |" for judge, found in result["subjects"].items()]
    return "\n".join(lines) + "\n"
