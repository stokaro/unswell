#!/usr/bin/env python3
"""Write RESULTS.md of the record of the fourth form of a closing denial from the recounted numbers.

verify.py calls render() with what it recounted from the data; this file holds no number of its own.
"""

LABELS = {
    "set-s": "Posts of the style-guide set",
    "human-blog": "Blog posts that people wrote before November 2022",
    "human-styled": "Articles that people wrote under a style guide",
    "human-docs": "Documentation pages that people wrote before November 2022",
    "model-guided-1": "Texts of the first writer model under a style guide",
    "model-guided-2": "Texts of the second writer model under a style guide",
    "model-plain-1": "Texts of the first writer model without a style guide",
    "model-plain-2": "Texts of the second writer model without a style guide",
    "fresh-1": "Fresh texts of the first writer model under a style guide",
    "fresh-2": "Fresh texts of the second writer model under a style guide",
    "public-today": "Pages of public repositories today",
    "panel": "Pages of the panel corpus that three models wrote or polished",
}
PARTS = {"fitting": "The fitting parts", "measured": "The measured parts", "whole": "Sets without parts"}
NOTES = {
    "fitting": "The fourth form was chosen on these pages.",
    "measured": "No part of the fourth form was chosen on these pages. The bars are read here. It is their second run: the "
                "first was the measurement of the rule with three forms.",
    "whole": "These sets have no parts and carry no bar.",
}


def percent(value):
    return f"{100 * value:.1f}%"


def cell(value):
    return f"{value['count']} of {value['of']}, {percent(value['share'])}"


def limit(bar):
    return f"{bar['kind'].split(',')[0]} {percent(bar['limit']) if bar['kind'].endswith('share') else bar['limit']}"


def bars_table(result):
    lines = ["| Bar | Number | Limit | Holds |", "| --- | --- | --- | --- |"]
    for bar in result["bars"]:
        name = bar["bar"]
        for key, label in LABELS.items():
            name = name.replace(key, label[0].lower() + label[1:])
        lines.append(f"| {name} | {cell(bar['value'])} | {limit(bar)} | {'yes' if bar['holds'] else '**no**'} |")
    return lines


def sets_table(result, part):
    lines = ["| Pages | Reported, three forms | Reported, four forms | Only with four | Closing denials counted, three forms | Four forms |",
             "| --- | --- | --- | ---: | ---: | ---: |"]
    for key, label in LABELS.items():
        found = result["sets"].get(f"{key}/{part}")
        if found:
            lines.append(f"| {label} | {cell(found['three'])} | {cell(found['four'])} | {found['added']} | {found['counted_three']} | "
                         f"{found['counted_four']} |")
    return lines


def render(result):
    lines = ["# Results: the fourth form of a closing denial", "",
             "Generated by `verify.py --write` from the data of this record. Do not edit.", "",
             f"`{result['rule']}` with three forms of a denial is the rule of `v0.1.0-alpha.19`. With four it is the build of this "
             "record. A page is reported when more than two of its paragraphs end on a denial and they are at least 8% of its "
             "paragraphs. A closing denial is counted with no limit on the page.", "",
             "## The bars", "",
             f"{result['bars_held']} of the {result['bars_total']} bars hold. They were written on issue 607 before the run on the "
             "measured parts.", ""]
    lines += bars_table(result)
    people, fresh = result["people_measured"], result["fresh_together"]
    lines += ["", f"The three kinds of human pages together are {people['pages']} pages: the rule reports {people['three']['count']} of "
              f"them with three forms and {people['four']['count']} with four. Of the {fresh['pages']} fresh model texts it reports "
              f"{fresh['three']['count']} and {fresh['four']['count']}."]
    lines += ["", f"Closing denials that three forms count and four do not, on all {sum(found['pages'] for found in result['sets'].values())} "
              f"pages of the record: {result['not_kept']}."]
    for part, title in PARTS.items():
        lines += ["", f"## {title}", "", NOTES[part], ""]
        lines += sets_table(result, part)
    return "\n".join(lines) + "\n"
